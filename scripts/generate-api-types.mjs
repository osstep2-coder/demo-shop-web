// Turns tests/api/generated/openapi.json into tests/api/generated/api.ts:
//   - one TypeScript type per component schema (Cart, Order, ...);
//   - ApiEndpoints: for every "METHOD /path" the request body, the `data` of a 200 response
//     and the error codes documented for each HTTP status (taken from the response descriptions).
// No dependencies on purpose: the spec uses a small subset of JSON Schema, and openapi-typescript
// does not support the TypeScript 7 this project is on.
import { readFile, writeFile } from "node:fs/promises";

const dir = new URL("../tests/api/generated/", import.meta.url);
const spec = JSON.parse(await readFile(new URL("openapi.json", dir), "utf8"));
const schemas = spec.components.schemas;

const refName = (ref) => ref.split("/").pop();
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

function toType(schema, indent = "") {
  if (schema.$ref) return refName(schema.$ref);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (schema.anyOf) return schema.anyOf.map((s) => toType(s, indent)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(toType(schema.items ?? {}, indent))}[]`;
    case "object":
      return schema.properties ? objectType(schema, indent) : "Record<string, unknown>";
    default:
      return "unknown";
  }
}

const wrap = (type) => (type.includes(" | ") ? `(${type})` : type);

function objectType(schema, indent) {
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const lines = Object.entries(schema.properties).map(([name, prop]) => {
    const doc = prop.description ? `${inner}/** ${prop.description} */\n` : "";
    return `${doc}${inner}${key(name)}${required.has(name) ? "" : "?"}: ${toType(prop, inner)};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/** `data` of a success envelope: CartResponse -> Cart. */
function successData(op) {
  const schema = op.responses?.["200"]?.content?.["application/json"]?.schema;
  if (!schema?.$ref) return "unknown";
  const envelope = schemas[refName(schema.$ref)];
  return envelope?.properties?.data ? toType(envelope.properties.data) : refName(schema.$ref);
}

function errorCodes(op) {
  const byStatus = Object.entries(op.responses ?? {})
    .filter(([status]) => /^[45]/.test(status))
    .map(([status, response]) => {
      const codes = [...(response.description ?? "").matchAll(/`([a-z_.]+)`/g)].map((m) => JSON.stringify(m[1]));
      return codes.length ? `      ${status}: ${codes.join(" | ")};` : null;
    })
    .filter(Boolean);
  return byStatus.length ? `{\n${byStatus.join("\n")}\n    }` : "{}";
}

const out = ["// Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit: run `npm run api:types`.", ""];

for (const [name, schema] of Object.entries(schemas)) {
  if (schema.description) out.push(`/** ${schema.description} */`);
  out.push(schema.type === "object" ? `export interface ${name} ${objectType(schema, "")}` : `export type ${name} = ${toType(schema)};`, "");
}

out.push("/** Every endpoint: request body, `data` of the 200 response, error codes per HTTP status. */", "export interface ApiEndpoints {");
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    const body = op.requestBody?.content?.["application/json"]?.schema;
    out.push(
      `  ${JSON.stringify(`${method.toUpperCase()} ${path}`)}: {`,
      `    request: ${body ? toType(body, "    ") : "never"};`,
      `    response: ${successData(op)};`,
      `    errors: ${errorCodes(op)};`,
      "  };",
    );
  }
}
out.push("}", "");

await writeFile(new URL("api.ts", dir), out.join("\n"));
console.log(`tests/api/generated/api.ts: ${Object.keys(schemas).length} schemas, ${Object.values(spec.paths).flatMap(Object.keys).length} endpoints`);
