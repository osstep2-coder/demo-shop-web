export function productMeta(sku: string, category: string): ProductMeta {
  return (
    META[sku] ?? {
      tagline: category,
      description: "Описание товара скоро появится. Уже сейчас его можно добавить в корзину и заказать.",
      specs: [
        ["Категория", category],
        ["Артикул", sku],
      ],
    }
  );
}

